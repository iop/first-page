const targets = await (await fetch("http://127.0.0.1:9333/json")).json();
const page = targets.find((t) => t.type === "page");
const ws = new WebSocket(page.webSocketDebuggerUrl);
await new Promise((r) => (ws.onopen = r));
let id = 0; const pending = new Map();
ws.onmessage = (e) => { const m = JSON.parse(e.data); if (pending.has(m.id)) { pending.get(m.id)(m); pending.delete(m.id); } };
const send = (method, params = {}) => new Promise((res) => { const i = ++id; pending.set(i, res); ws.send(JSON.stringify({ id: i, method, params })); });
const evalJs = async (expression) => (await send("Runtime.evaluate", { expression, awaitPromise: true, returnByValue: true })).result.result.value;
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
await send("Page.enable"); await send("Runtime.enable");
await send("Emulation.setDeviceMetricsOverride", { width: 1440, height: 1100, deviceScaleFactor: 1, mobile: false });
await send("Page.navigate", { url: "http://localhost:5174/" });
await sleep(1500);
const rowCount = () => evalJs(`document.querySelectorAll('[data-slot="table"] tbody tr').length`);
const queueCount = () => evalJs(`[...document.querySelectorAll('span')].filter(s => s.textContent==='Retry').length`);
const tab = (label) => evalJs(`(() => { const t=[...document.querySelectorAll('[role="tab"]')].find(x=>x.textContent.trim()==='${label}'); t && t.click(); return !!t })()`);
console.log("initial all-table rows:", await rowCount(), "| Retry buttons:", await queueCount());
await tab("Failing"); await sleep(300);
console.log("after Failing tab, table rows:", await rowCount());
await tab("Running"); await sleep(300);
console.log("after Running tab, table rows:", await rowCount());
await tab("All"); await sleep(300);
console.log("back to All, table rows:", await rowCount());
const clickRetry = await evalJs(`(() => { const b=[...document.querySelectorAll('button')].find(x=>x.textContent.trim()==='Retry'); b && b.click(); return !!b })()`);
await sleep(300);
console.log("clicked Retry:", clickRetry, "| Retry buttons now:", await queueCount(), "| Running badges in queue:", await evalJs(`[...document.querySelectorAll('[data-slot="badge"]')].filter(b=>b.textContent.trim()==='Running').length`));
ws.close();
